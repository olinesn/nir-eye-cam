#!/usr/bin/env python3
"""Draw README.md's "Parts and wiring" section from docs/wiring.yml.

    python3 scripts/wiring.py           # rewrite the section in README.md
    python3 scripts/wiring.py --check   # exit 1 if it is out of date (pre-commit)

Each build in docs/wiring.yml becomes a Mermaid diagram (GitHub renders it)
and a parts table. Pins are written as {MACRO} and read from the firmware's
pin header, so the diagram shows the pins the firmware actually uses, and a
macro the header does not define is an error.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "docs" / "wiring.yml"
README = ROOT / "README.md"
BEGIN = "<!-- wiring:begin -->"
END = "<!-- wiring:end -->"

DEFINE = re.compile(r"^\s*#define\s+(\w+)\s+(-?(?:0x[0-9A-Fa-f]+|\d+))\b\s*(?://\s*(.*))?$")
CONDITION = re.compile(r"^\s*#(if|elif|else|endif)\b(.*)$")
PLACEHOLDER = re.compile(r"\{(\w+)(:value)?\}")


class WiringError(Exception):
    pass


def read_pins(path: Path, variant: str | None) -> dict[str, tuple[int, str]]:
    """{macro: (value, note)} for the numeric #defines of a pin header.

    With a variant, only that #if defined(VARIANT) branch (plus everything
    outside #if blocks) is read; the header's other boards are skipped.
    """
    pins: dict[str, tuple[int, str]] = {}
    depth, taking, taken = 0, True, False
    for line in path.read_text().splitlines():
        cond = CONDITION.match(line)
        if cond and variant and not line.lstrip().startswith("#ifndef"):
            kind, rest = cond.groups()
            if kind == "if":
                depth += 1
                taking = taken = variant in rest
            elif kind == "elif":
                taking = not taken and variant in rest
                taken = taken or taking
            elif kind == "else":
                taking = not taken
            elif depth:
                depth, taking = depth - 1, True
            continue
        if depth and not taking:
            continue
        m = DEFINE.match(line)
        if m:
            name, value, comment = m.groups()
            note = (comment or "").split()[0] if (comment or "").strip() else ""
            pins[name] = (int(value, 0), note)
    return pins


def expand(text: str, pins: dict[str, tuple[int, str]], pin_format: str, where: str) -> str:
    def one(m: re.Match) -> str:
        name, bare = m.group(1), m.group(2)
        if name not in pins:
            raise WiringError(f"{where}: {{{name}}} is not #defined in the pin header")
        value, note = pins[name]
        if bare:
            return str(value)
        return pin_format.format(value=value, note=note).replace(" ()", "")

    return PLACEHOLDER.sub(one, text)


def mermaid_text(text: str) -> str:
    return text.replace('"', "#quot;")


def table_text(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render_build(build: dict) -> list[str]:
    pins = read_pins(ROOT / build["pins"], build.get("variant"))
    parts = {p["id"]: p for p in build["parts"]}
    linked = set()
    edges = []
    for n, link in enumerate(build.get("links", []), start=1):
        for end in (link["from"], link["to"]):
            if end not in parts:
                raise WiringError(f"{build['id']}: link {n} names an unknown part '{end}'")
            linked.add(end)
        signals = [expand(s, pins, build["pin_format"], f"{build['id']}: link {n}") for s in link["signals"]]
        label = mermaid_text("<br/>".join(signals))
        edges.append(f'    {link["from"]} -- "{label}" --> {link["to"]}')

    out = [f"### {build['title']}", ""]
    if build.get("about"):
        out += [" ".join(build["about"].split()), ""]
    out += ["```mermaid", "flowchart LR"]
    out += [f'    {p["id"]}["{mermaid_text(p["name"])}"]' for p in build["parts"] if p["id"] in linked]
    out += edges
    out += ["```", "", "| Part | Notes |", "|---|---|"]
    out += [f"| **{table_text(p['name'])}** | {table_text(p.get('notes', ''))} |" for p in build["parts"]]
    out += [""]
    return out


def render(spec: dict) -> str:
    lines = [
        BEGIN,
        ("<!-- Generated by scripts/wiring.py from docs/wiring.yml and the firmware's pin headers."
         " Edit those, then run: python3 scripts/wiring.py -->"),
        "",
    ]
    for build in spec["builds"]:
        lines += render_build(build)
    lines.append(END)
    return "\n".join(lines)


def updated_readme(readme: str, section: str) -> str:
    if readme.count(BEGIN) != 1 or readme.count(END) != 1:
        raise WiringError(f"README.md needs exactly one {BEGIN} and one {END}")
    head, rest = readme.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + section + tail


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if README.md is out of date")
    args = ap.parse_args(argv)
    try:
        readme = README.read_text()
        new = updated_readme(readme, render(yaml.safe_load(SPEC.read_text())))
    except (WiringError, OSError, KeyError, yaml.YAMLError) as e:
        print(f"wiring: {e}", file=sys.stderr)
        return 1
    if new == readme:
        return 0
    if args.check:
        print("wiring: README.md's Parts and wiring section is out of date. "
              "Run: python3 scripts/wiring.py", file=sys.stderr)
        return 1
    README.write_text(new)
    print("wiring: updated README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
